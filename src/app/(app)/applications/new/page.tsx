import { pageGuard } from "@/server/session";
import { listFormOptions } from "@/server/applications";
import { PageHeader } from "@/components/page-header";
import { AccessDenied } from "@/components/access-denied";
import { NewApplicationForm } from "@/components/app/new-application-form";

export const metadata = { title: "Create application" };

export default async function NewApplicationPage() {
  const { actor, denied } = await pageGuard("application.create");
  const crumbs = [{ label: "Applications", href: "/applications" }, { label: "Create" }];
  if (denied) return (<><PageHeader title="Create application" crumbs={crumbs} /><AccessDenied /></>);
  const { institutions, templates } = await listFormOptions(actor);
  return (
    <>
      <PageHeader title="Create application" crumbs={crumbs} description="The application ID is generated by the server. Institution details are pre-filled from the institutional record and can be edited — differences are checked against the record during validation." />
      <NewApplicationForm
        institutions={institutions.map((i) => ({ id: i.id, code: i.code, name: i.name, category: i.category, programmes: i.programmes.map((p) => ({ name: p.name, level: p.level, intake: p.approvedIntake })) }))}
        templates={templates.map((t) => ({ code: t.code, name: t.name, description: t.description }))}
        defaultContact={actor.role === "APPLICANT" ? { name: actor.name, email: actor.email } : null}
      />
    </>
  );
}
